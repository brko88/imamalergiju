const LANG_KEY = 'imamalergiju:lang';

function getLang() {
  return localStorage.getItem(LANG_KEY) || 'bs';
}

function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
}

function localeForLang(lang) {
  if (lang === 'en') return 'en-GB';
  if (lang === 'de') return 'de-DE';
  return 'bs-BA';
}

